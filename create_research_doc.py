from docx import Document
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.style import WD_STYLE_TYPE

# إنشاء مستند جديد
doc = Document()

# تعديل نمط النص العادي
style_normal = doc.styles['Normal']
font = style_normal.font
font.name = 'Traditional Arabic'
font.size = Pt(14)

# دالة لإضافة عنوان رئيسي
def add_heading(text, level=1):
    if level == 0:  # العنوان الرئيسي
        heading = doc.add_paragraph()
        run = heading.add_run(text)
        run.bold = True
        run.font.size = Pt(18)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif level == 1:  # العناوين الفرعية (مثل "مقدمة"، "١. المتغير التابع...")
        heading = doc.add_paragraph()
        run = heading.add_run(text)
        run.bold = True
        run.font.size = Pt(16)
        heading.alignment = WD_ALIGN_PARAGRAPH.LEFT
    doc.add_paragraph()  # سطر فارغ بعد العنوان

# دالة لإضافة فقرة عادية
def add_paragraph(text):
    p = doc.add_paragraph(text)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.0

# دالة لإضافة قائمة نقطية
def add_bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    p.add_run(text)
    p.paragraph_format.space_after = Pt(4)

